import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
await page.addInitScript(()=>{Element.prototype.requestPointerLock=()=>{};Element.prototype.setPointerCapture=()=>{};});
await page.goto('http://127.0.0.1:4173/',{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Explore Dentsu',exact:true}).click();await page.waitForTimeout(900);
await page.locator('dialog').evaluate(el=>el.scrollTop=el.scrollHeight);
await page.waitForTimeout(150);const closeBounds=await page.getByRole('button',{name:'Close details'}).boundingBox();
if(closeBounds.y<0||closeBounds.y>800)throw Error('Close control not sticky');
await page.screenshot({path:'artifacts/mobile-dentsu-end.png'});
await page.getByRole('button',{name:'Close details'}).click();await page.locator('dialog').waitFor({state:'detached'});
await page.getByRole('button',{name:'View credentials & education'}).click();
if(await page.locator('.full-credentials > div').count()!==6)throw Error('Credentials missing');
await page.getByText('Andhra University',{exact:false}).waitFor();
await page.getByRole('button',{name:'Back to the portfolio'}).click();await page.locator('dialog').waitFor({state:'detached'});
await page.locator('.platform-marquee').scrollIntoViewIfNeeded();
await page.getByRole('button',{name:'Pause platform motion'}).click();
if(await page.locator('.ticker-track').evaluate(el=>getComputedStyle(el).animationPlayState)!=='paused')throw Error('Ticker pause failed');
const tickerNames=await page.locator('.ticker-group').first().locator('button').allTextContents();
if(tickerNames.length!==29)throw Error('All platforms not in motion');
await page.getByRole('button',{name:'Resume platform motion'}).click();
await page.locator('.ticker-group').first().locator('button').first().focus();
await page.keyboard.press('Enter');await page.getByRole('dialog').waitFor();
await page.locator('dialog').click({position:{x:2,y:2}});await page.locator('dialog').waitFor({state:'detached'});
await browser.close();console.log(JSON.stringify({stickyClose:true,credentials:6,tickerPlatforms:29,pauseResume:true,keyboardOpen:true,backdropClose:true}));
